// The answers. On an unbounded board (a window far wider than any trip here
// can reach), the fewest moves; then the same inside the puzzle's window, the
// number of shortest trips both ways, and the fewest without a left step.
export const OPEN = {levels: 10, xmin: -400, xmax: 600};
export function countTrips(q, target) {
  const dist = distances(q, target), memo = new Map();
  const count = place => {
    const id = place.join(), d = dist.get(id);
    if (d === 0) return 1;
    if (!memo.has(id)) memo.set(id, DIRS.reduce((sum, dir) => { const next = go(q, place, dir); return sum + (next && dist.get(next.join()) === d - 1 ? count(next) : 0); }, 0));
    return memo.get(id);
  };
  return count([0, 0]);
}
export function noLeft(q, target) {
  const seen = new Map([['0,0', 0]]), queue = [[0, 0]];
  for (let i = 0; i < queue.length; i++) for (const dir of ['U', 'D', 'R']) {
    const next = go(q, queue[i], dir);
    if (next && !seen.has(next.join())) { seen.set(next.join(), seen.get(queue[i].join()) + 1); queue.push(next); }
  }
  return seen.get(`${target},0`);
}
// The farthest ground coordinate a trip of at most n moves can end at, by
// breadth-first search to depth n, and the bound max over H of (n − 2H)·2^H.
export const bound = n => Math.max(...Array.from({length: Math.floor(n / 2) + 1}, (_, H) => (n - 2 * H) * 2 ** H));
export function farthestIn(q, n) {
  const seen = new Map([['0,0', 0]]), queue = [[0, 0]];
  let best = 0;
  for (let i = 0; i < queue.length; i++) {
    const d = seen.get(queue[i].join());
    if (queue[i][1] === 0) best = Math.max(best, queue[i][0]);
    if (d === n) continue;
    for (const dir of DIRS) { const next = go(q, queue[i], dir); if (next && !seen.has(next.join())) { seen.set(next.join(), d + 1); queue.push(next); } }
  }
  return best;
}
function solve(item) {
  const window = item.parameters;
  let target = window.target;
  if (item.farthest) {
    target = farthestIn(OPEN, item.farthest);
    if (target !== bound(item.farthest)) throw Error(`farthest in ${item.farthest}: search ${target}, bound ${bound(item.farthest)}`);
    if (farthestIn(window, item.farthest) !== target) throw Error(`puzzle ${item.number}: the window changes the farthest`);
  }
  const q = {...window, target}, budget = fewest(OPEN, [0, 0], target);
  if (item.farthest && budget !== item.farthest) throw Error(`puzzle ${item.number}: ${target} takes ${budget}, not ${item.farthest}`);
  if (window.levels > 6 || fewest(q, [0, 0]) !== budget) throw Error(`puzzle ${item.number}: the window loses a shortest trip`);
  const trips = countTrips(q, target), open = countTrips(OPEN, target);
  if (trips !== open) throw Error(`puzzle ${item.number}: ${open} shortest trips, ${trips} in the window`);
  return {q: {...q, budget, ...(item.farthest ? {farthest: true} : {})}, solution: {word: shortestTrip(q), fewest: budget, trips, ...(item.difficulty_level === 'hard' && !item.farthest ? {noLeft: noLeft(OPEN, target)} : {})}};
}
